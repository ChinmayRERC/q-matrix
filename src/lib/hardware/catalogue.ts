/** Counts per category, used for the filter chips. */
export function categoryCounts(): Record<HardwareCategory, number> {
  return HARDWARE.reduce(
    (acc, item) => {
      acc[item.category] += 1
      return acc
    },
    { machine: 0, control: 0, cryo: 0, optics: 0, sensor: 0, actuator: 0 } as Record<HardwareCategory, number>,
  )
}

/** Filter by category and a free-text query over name, maker, tags and copy. */
export function filterHardware(category: HardwareCategory | 'all', query: string): HardwareItem[] {
  const q = query.trim().toLowerCase()
  return HARDWARE.filter((item) => {
    if (category !== 'all' && item.category !== category) return false
    if (!q) return true
    return `${item.name} ${item.maker} ${item.what} ${item.why} ${item.tags.join(' ')}`.toLowerCase().includes(q)
  })
}
